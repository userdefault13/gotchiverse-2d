// Keccak-256 as Ethereum uses it (original Keccak padding, not NIST SHA3), for keystore MACs and addresses.
// Node's crypto only ships SHA3. Lanes are BigInt: slow, but only ever hashes a few dozen bytes here.

const MASK = (1n << 64n) - 1n;

/** Round constants from the Keccak LFSR, so none are typed in by hand. */
const RC: bigint[] = (() => {
  let r = 1;
  const bit = () => {
    const out = r & 1;
    r = r & 0x80 ? ((r << 1) ^ 0x171) & 0xff : (r << 1) & 0xff;
    return out;
  };
  return Array.from({ length: 24 }, () => {
    let c = 0n;
    for (let j = 0; j < 7; j++) if (bit()) c |= 1n << BigInt((1 << j) - 1);
    return c;
  });
})();

/** Rotation offset per lane (index x + 5y), generated by walking (x, y) → (y, 2x + 3y). */
const ROT: number[] = (() => {
  const r = new Array(25).fill(0);
  let x = 1;
  let y = 0;
  for (let t = 0; t < 24; t++) {
    r[x + 5 * y] = (((t + 1) * (t + 2)) / 2) % 64;
    [x, y] = [y, (2 * x + 3 * y) % 5];
  }
  return r;
})();

const rotl = (v: bigint, n: number) => (n === 0 ? v : ((v << BigInt(n)) | (v >> BigInt(64 - n))) & MASK);

function permute(a: bigint[]): void {
  for (let round = 0; round < 24; round++) {
    const c = [0, 1, 2, 3, 4].map((x) => a[x] ^ a[x + 5] ^ a[x + 10] ^ a[x + 15] ^ a[x + 20]);
    for (let x = 0; x < 5; x++) {
      const d = c[(x + 4) % 5] ^ rotl(c[(x + 1) % 5], 1);
      for (let y = 0; y < 25; y += 5) a[x + y] ^= d;
    }
    const b = new Array<bigint>(25);
    for (let x = 0; x < 5; x++) for (let y = 0; y < 5; y++) b[y + 5 * ((2 * x + 3 * y) % 5)] = rotl(a[x + 5 * y], ROT[x + 5 * y]);
    for (let x = 0; x < 5; x++) for (let y = 0; y < 25; y += 5) a[x + y] = b[x + y] ^ (~b[((x + 1) % 5) + y] & MASK & b[((x + 2) % 5) + y]);
    a[0] ^= RC[round];
  }
}

export function keccak256(data: Uint8Array): Uint8Array {
  const rate = 136;
  const padded = new Uint8Array(Math.ceil((data.length + 1) / rate) * rate);
  padded.set(data);
  padded[data.length] ^= 0x01;
  padded[padded.length - 1] ^= 0x80;
  const state = new Array<bigint>(25).fill(0n);
  for (let off = 0; off < padded.length; off += rate) {
    for (let i = 0; i < rate / 8; i++) {
      let lane = 0n;
      for (let k = 7; k >= 0; k--) lane = (lane << 8n) | BigInt(padded[off + i * 8 + k]);
      state[i] ^= lane;
    }
    permute(state);
  }
  const out = new Uint8Array(32);
  for (let i = 0; i < 4; i++) for (let k = 0; k < 8; k++) out[i * 8 + k] = Number((state[i] >> BigInt(8 * k)) & 0xffn);
  return out;
}
